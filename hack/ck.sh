cargo_green_setup() {
    [[ $# -eq 0 ]]
    cat <<EOF
    - name: Setup
      run: |
        if ! cargo green supergreen setup; then
            { cargo green supergreen setup 2>/dev/null || true; } | sudo /bin/sh -xe
        fi
EOF
